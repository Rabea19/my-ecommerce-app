import { test, expect } from '@playwright/test';

async function fits(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
}
test('responsive storefront through checkout, admin cancellation and customer status', async ({ page, browser }, info) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Little finds. Everyday joy.' })).toBeVisible();
  await fits(page);
  await page.screenshot({ path: info.outputPath('home.png'), fullPage: true });
  await page.getByRole('button', { name: info.project.name === 'desktop' ? 'Account menu' : 'Open menu', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Explore market' })).toBeVisible();
  await page.getByRole('button', { name: 'Close menu' }).click();
  await page.getByRole('textbox', { name: 'Search products' }).fill('Browser test phone');
  await page.getByRole('button', { name: 'Submit search' }).click();
  await expect(page.getByRole('heading', { name: 'Browser test phone' })).toBeVisible();
  await fits(page);
  await page.getByRole('heading', { name: 'Browser test phone' }).getByRole('link').click();
  await expect(page.getByRole('heading', { name: 'Browser test phone' })).toBeVisible();
  await fits(page);
  await page.getByRole('button', { name: 'Add to bag', exact: true }).click();
  await page.getByRole('link', { name: 'Shopping bag, 1 items', exact: true }).click();
  await page.getByRole('button', { name: 'Increase Browser test phone quantity' }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Shopping bag (2)' })).toBeVisible();
  await fits(page);
  await page.screenshot({ path: info.outputPath('cart.png'), fullPage: true });
  await page.getByRole('link', { name: 'Continue to checkout →' }).click();
  await expect(page.getByRole('heading', { name: 'Lovely to see you.' })).toBeVisible();
  await fits(page);
  await page.getByRole('button', { name: 'New here? Create an account' }).click();
  await page.getByLabel('Email address').fill(`buyer-${info.project.name}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill('TestOnlyPassword123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review your order' })).toBeVisible();
  await fits(page);
  await page.screenshot({ path: info.outputPath('checkout.png'), fullPage: true });
  const response = page.waitForResponse(r => r.url().endsWith('/api/orders') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Confirm order' }).click();
  const orderResponse = await response;
  expect(orderResponse.status()).toBe(201);
  const order = await orderResponse.json();
  expect(order.total_price).toBe(250);
  await expect(page.getByRole('heading', { name: 'Thank you for your order.' })).toBeVisible();
  await page.getByRole('link', { name: 'View my orders' }).click();
  await expect(page.getByText('pending', { exact: true })).toBeVisible();
  await fits(page);
  await page.screenshot({ path: info.outputPath('orders.png'), fullPage: true });

  const admin = await browser.newContext({ baseURL: 'http://localhost:4000', viewport: { width: 1440, height: 900 } });
  const adminPage = await admin.newPage();
  await adminPage.goto('/admin/login');
  await adminPage.getByPlaceholder('Email', { exact: true }).fill('admin@example.test');
  await adminPage.getByPlaceholder('Password', { exact: true }).fill('TestOnlyPassword123');
  await adminPage.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(adminPage).toHaveURL(/\/admin\/?$/);
  await adminPage.goto('/admin/orders');
  const row = adminPage.getByRole('row').filter({ hasText: order.id });
  await expect(row).toBeVisible();
  const update = adminPage.waitForResponse(r => r.url().endsWith(`/api/orders/${order.id}`) && r.request().method() === 'PATCH');
  await row.getByRole('combobox').selectOption('canceled');
  expect((await update).status()).toBe(200);
  await expect(row.getByRole('combobox')).toHaveValue('canceled');
  await adminPage.screenshot({ path: info.outputPath('admin-order.png'), fullPage: true });
  await page.getByRole('button', { name: 'Refresh status' }).click();
  await expect(page.getByText('canceled', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('canceled', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
  await admin.close();
});
