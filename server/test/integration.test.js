import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import request from 'supertest';
import { createApp } from '../src/app.js';
import { User, Product, Order } from '../src/models.js';
import { hashPassword } from '../src/security.js';
let repl, app, admin, customer;
before(async()=>{
 repl=await MongoMemoryReplSet.create({ replSet:{count:1} });await mongoose.connect(repl.getUri());await Promise.all([User.init(),Order.init()]);
 app=createApp();admin=request.agent(app);customer=request.agent(app);
 await User.create({email:'admin@example.com',passwordHash:await hashPassword('SecurePassword123'),role:'admin'});
 await admin.post('/api/auth/login').send({email:'admin@example.com',password:'SecurePassword123',admin:true}).expect(200);
 await customer.post('/api/auth/register').send({email:'buyer@example.com',password:'SecurePassword123',role:'admin'}).expect(200);
});
after(async()=>{await mongoose.disconnect();await repl?.stop();});
test('shared catalog, secure checkout, stock rollback, idempotency and cancellation',async()=>{
 await customer.post('/api/products').send({}).expect(403);
 await request(app).get('/api/users').expect(401);
 await customer.get('/api/users').expect(403);
 const product=(await admin.post('/api/products').send({name:'Phone',price:99.95,stock:4,category:'Mobiles'}).expect(201)).body;
 assert.equal((await request(app).get('/api/products')).body[0].id,product.id);
 const payload={products:[{id:product.id,quantity:2,price:0.01}],total_price:0.02};
 const order=(await customer.post('/api/orders').set('Idempotency-Key','checkout-test-key-0001').send(payload).expect(201)).body;
 assert.equal(order.total_price,199.9);assert.equal((await Product.findById(product.id)).stock,2);
 await customer.post('/api/orders').set('Idempotency-Key','checkout-test-key-0001').send(payload).expect(200);
 assert.equal((await Product.findById(product.id)).stock,2);
 assert.equal((await admin.get('/api/orders')).body[0].id,order.id);
 await customer.patch('/api/orders/'+order.id).send({status:'completed'}).expect(403);
 await customer.post('/api/orders').set('Idempotency-Key','checkout-test-key-0002').send({products:[{id:product.id,quantity:3}]}).expect(409);
 assert.equal((await Product.findById(product.id)).stock,2);
 await admin.patch('/api/orders/'+order.id).send({status:'canceled'}).expect(200);
 await admin.patch('/api/orders/'+order.id).send({status:'canceled'}).expect(200);
 assert.equal((await Product.findById(product.id)).stock,4);
 await admin.patch('/api/orders/'+order.id).send({status:'completed'}).expect(409);
 const other=request.agent(app);await other.post('/api/auth/register').send({email:'other@example.com',password:'SecurePassword123'}).expect(200);
 assert.equal((await other.get('/api/orders')).body.length,0);
 await other.post('/api/auth/login').send({email:'other@example.com',password:'SecurePassword123',admin:true}).expect(403);
 await request(app).post('/api/auth/login').set('Origin','https://attacker.example').send({}).expect(403);
 const users=(await admin.get('/api/users')).body;assert.ok(users.every(u=>!u.passwordHash));assert.equal(users.find(u=>u.email==='buyer@example.com').role,'customer');
 await customer.post('/api/auth/logout').expect(200);await customer.get('/api/orders').expect(401);
});
test('concurrent checkouts cannot oversell and multi-item failure rolls back',async()=>{
 await customer.post('/api/auth/login').send({email:'buyer@example.com',password:'SecurePassword123'}).expect(200);
 const p=await Product.create({name:'Last one',price:10,stock:1,category:'Tablets'});
 const results=await Promise.all(['concurrent-key-00001','concurrent-key-00002'].map(key=>customer.post('/api/orders').set('Idempotency-Key',key).send({products:[{id:p.id,quantity:1}]})));
 assert.deepEqual(results.map(r=>r.status).sort(),[201,409]);assert.equal((await Product.findById(p.id)).stock,0);
 const q=await Product.create({name:'Available',price:20,stock:2,category:'Tablets'});
 await customer.post('/api/orders').set('Idempotency-Key','rollback-test-00001').send({products:[{id:q.id,quantity:1},{id:p.id,quantity:1}]}).expect(409);
 assert.equal((await Product.findById(q.id)).stock,2);
});

test('profile changes require a session and cannot escalate permissions', async()=>{
 await request(app).patch('/api/auth/profile').send({name:'Guest'}).expect(401);
 await customer.post('/api/auth/login').send({email:'buyer@example.com',password:'SecurePassword123'}).expect(200);
 await customer.patch('/api/auth/profile').send({name:'Buyer',role:'admin'}).expect(400);
 await customer.patch('/api/auth/profile').send({name:'Buyer',email:'admin@example.com'}).expect(400);
 await customer.patch('/api/auth/profile').send({name:'   '}).expect(400);
 const result=await customer.patch('/api/auth/profile').send({name:'Updated Buyer'}).expect(200);
 assert.equal(result.body.user.name,'Updated Buyer');assert.equal(result.body.user.role,'customer');
 assert.equal((await customer.get('/api/auth/session')).body.user.name,'Updated Buyer');
 await customer.get('/api/users').expect(403);
});
